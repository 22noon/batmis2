#!/usr/bin/env python3
"""Alternating rank-trace replay and full-mapper checkpoint-spacing trials."""
import argparse
import hashlib
import itertools
import json
import os
import re
import resource
import subprocess
import time


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def app_timing(stderr):
    line = next((s for s in stderr.splitlines() if " timing:" in s), None)
    if line is None:
        raise RuntimeError(f"Missing mapper timing line: {stderr}")
    out = {}
    for k, v in re.findall(r"([a-z_]+)=([0-9.]+)s", line):
        out[k] = float(v)
    for k in ("records", "reported_hits"):
        m = re.search(rf"{k}=(\d+)", line)
        if not m:
            raise RuntimeError(f"Missing {k} in {line}")
        out[k] = int(m.group(1))
    return out


def process(command, metadata, phase, spacing, trial, position, kind):
    before = os.getloadavg()
    cpu0 = resource.getrusage(resource.RUSAGE_CHILDREN).ru_utime
    t0 = time.monotonic()
    p = subprocess.run(command, text=True, capture_output=True, check=True)
    wall = time.monotonic() - t0
    cpu = resource.getrusage(resource.RUSAGE_CHILDREN).ru_utime - cpu0
    row = {
        **metadata,
        "phase": phase,
        "spacing": spacing,
        "trial": trial,
        "order_position": position,
        "command": command,
        "external_wall_s": wall,
        "user_cpu_s": cpu,
        "load_before": before,
        "load_after": os.getloadavg(),
    }
    if kind == "rank":
        line = next(s for s in p.stdout.splitlines() if s.startswith("replay:"))
        row.update({k: int(v) if k in ("queries", "checksum", "occ_minor_bytes", "occ_major_bytes") else float(v)
                    for k, v in re.findall(r"([a-z_]+)=([0-9.]+)", line)})
    else:
        row.update(app_timing(p.stderr))
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build-root", required=True)
    ap.add_argument("--reads", required=True)
    ap.add_argument("--trace", required=True)
    ap.add_argument("--trials", type=int, default=10)
    ap.add_argument("--rank-output", required=True)
    ap.add_argument("--mapper-output", required=True)
    a = ap.parse_args()
    root = os.path.abspath(a.build_root)
    spaces = (64, 128, 256, 512, 1024)
    metadata = {
        "reads": os.path.abspath(a.reads),
        "reads_sha256": sha256(a.reads),
        "trace": os.path.abspath(a.trace),
        "trace_sha256": sha256(a.trace),
        "workload": "100000 100bp reads; rank trace generated by 256-row exact-search build",
    }
    configs = {}
    for s in spaces:
        d = os.path.join(root, str(s))
        prefix = os.path.join(d, "ref.fa")
        configs[s] = {
            "rank": os.path.join(d, "rank_replay"),
            "mapper": os.path.join(d, "batman_zero_structured"),
            "prefix": prefix,
            "bwt": prefix.rsplit("/", 1)[0] + "/revref.fa.bwt",
            "fmv": prefix.rsplit("/", 1)[0] + "/revref.fa.fmv",
        }
        metadata[f"binary_{s}_sha256"] = sha256(configs[s]["mapper"])
        metadata[f"rank_binary_{s}_sha256"] = sha256(configs[s]["rank"])
        metadata[f"bwt_{s}_sha256"] = sha256(configs[s]["bwt"])
        metadata[f"fmv_{s}_sha256"] = sha256(configs[s]["fmv"])
    metadata["read_file"] = a.reads

    # One unrecorded warm-up per configuration and phase.
    for s in spaces:
        c = configs[s]
        subprocess.run([c["rank"], c["bwt"], c["fmv"], a.trace], capture_output=True, check=True)
        subprocess.run([c["mapper"], "-q", a.reads, "-g", c["prefix"], "-m", "0", "--quiet", "--timing"], capture_output=True, check=True)

    orders = []
    for i in range(5):
        rotated = spaces[i:] + spaces[:i]
        orders.append(rotated)
    for i in range(5):
        orders.append(list(reversed(orders[i])))

    outputs = {"rank": [], "mapper": []}
    for trial in range(1, a.trials + 1):
        order = orders[(trial - 1) % len(orders)]
        for pos, s in enumerate(order, 1):
            c = configs[s]
            cmd = [c["rank"], c["bwt"], c["fmv"], a.trace]
            r = process(cmd, metadata, "rank_replay", s, trial, pos, "rank")
            outputs["rank"].append(r)
            print(json.dumps(r, sort_keys=True), flush=True)
        for pos, s in enumerate(order, 1):
            c = configs[s]
            cmd = [c["mapper"], "-q", a.reads, "-g", c["prefix"], "-m", "0", "--quiet", "--timing"]
            r = process(cmd, metadata, "full_mapper", s, trial, pos, "mapper")
            outputs["mapper"].append(r)
            print(json.dumps(r, sort_keys=True), flush=True)

    rank_checksums = {r["checksum"] for r in outputs["rank"]}
    mapper_counts = {(r["records"], r["reported_hits"]) for r in outputs["mapper"]}
    if len(rank_checksums) != 1:
        raise SystemExit(f"Rank replay checksum mismatch: {rank_checksums}")
    if mapper_counts != {(100000, 75000)}:
        raise SystemExit(f"Mapper record/hit mismatch: {mapper_counts}")
    for kind, dest in (("rank", a.rank_output), ("mapper", a.mapper_output)):
        with open(dest, "w") as f:
            for row in outputs[kind]:
                f.write(json.dumps(row, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
